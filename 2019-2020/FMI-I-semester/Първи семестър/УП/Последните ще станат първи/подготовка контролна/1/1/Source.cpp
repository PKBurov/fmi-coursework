using namespace std;
#include <iostream>
#include <cmath>

int main()
{
	/*Напишете програма на C++, която приема от стандартния вход две цели положителни числа (x, n). 
	Програмата трябва да валидира входа докато не бъдат въведени коректни данни. 
	След това да пресметне x * n като използва алгоритъм за „бързо“ умножение на две числа, който гласи следното:   

	x * n = | 2 * x * (n / 2) |   за n четно число;           
	x + x * (n - 1)       за n нечетно число;   
Алгоритъмът да се реализира итеративно докато n не стане 0. Накрая да се изведе резултата от умножението.   */

	unsigned int x,n,s=1;
	cin >> x >> n;
	while (n != 0)
	{
		if (n % 2 == 0)
		{
			s = fabs(2 * x*(n / 2));

		}
		else
		{
			s = x + x*(n - 1);
		}

		cout << "x * n = " << s << endl;
		n--;
	}
	
	return 0;
}