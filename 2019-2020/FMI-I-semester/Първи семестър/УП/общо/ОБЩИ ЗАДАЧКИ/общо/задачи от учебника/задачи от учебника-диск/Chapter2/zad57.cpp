#include <iostream.h>

int main()
{
    int n;
    do
    {
        cout << "Въведете положително цяло число ";
        cin >> n;
    } while(n <= 0);

    // намиране на сумата от цифрите на n
    int s = 0;
    int k = n;
    while(k > 0)
    {
        s = s + k % 10;
        k = k / 10;
    }
    // проверка дали сумата от цифрите се дели на 3
    if(s % 3 == 0)
    {
        cout << "Сумата от цифрите на " << n
             << " се дели на 3. \n";
    }
    else
    {
        cout << "Сумата от цифрите на " << n
             << " не се дели на 3. \n";
    }
    return 0;
}
