#include <iostream.h>

int main()
{
    int x = 0,
        y = 0,
        flags = 0,
        digit = 0;
    cout << "Въведете неотрицателно цяло число: ";
    cin >> x;
    cout << "Въведете неотрицателно цяло число: ";
    cin >> y;

    if(y == 0)
    {
        // активира се нулевият по ред бит
        // на flags, за да се означи наличието
        // на единствена нула в числото
        flags = 1;
    }
    else
    {
        while(y != 0)
        {   // активира се битът, съответен
            // на най-дясната цифра на числото
            flags = flags | 1 << y % 10;
            y /= 10;
        }
    }

    // Проверява се дали x е нула и тя се съдържа в y
    if(x == 0 && (flags & 1) != 1)
    {
        cout << "Свойството не е в сила.\n ";
    }
    else
    {   // следващият цикъл завършва, когато числото x стане 0
        // или се намери цифра на x, която не се среща в y
        while(x != 0 && flags & 1 << x % 10)
        {
            x /= 10;
        }
        if(x == 0)
        {
            cout << "Свойството е в сила.\n";
        }
        else
        {
            cout << "Свойството не е в сила.\n";
        }
    }
    return 0;
}
