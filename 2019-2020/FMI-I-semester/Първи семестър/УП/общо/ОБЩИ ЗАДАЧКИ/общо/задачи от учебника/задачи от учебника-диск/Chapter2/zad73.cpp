#include <iostream.h>

int main()
{ 
    int a = 0,				    // 0-вото число на Фибоначи
        b = 1,		            // 1-вото число на Фибоначи
        x = 0,	                // дадено число на Фибоначи
        n = 0,	 // пореден номер на даденото число в редицата
        tmp = 0;
    cout << "Въведете число на Фибоначи: ";
    cin >> x;

    // намиране на мястото на числото в редицата
    while(a < x)
    { 
        tmp = b;
        b = a + b;
        a = tmp;
        n++;
    }

    if(a != x)
    {
        cout << x << " не е число на Фибоначи\n";
    }
    else
    {
        cout << "Поредният номер на " << x
             << " е: " << n << "\n";
    }
    return 0;
}
