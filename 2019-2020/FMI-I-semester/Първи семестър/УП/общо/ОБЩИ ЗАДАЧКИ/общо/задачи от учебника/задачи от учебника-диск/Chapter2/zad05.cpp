#include <iostream.h>

int main()
{
    // деклариране и въвеждане на стойности
    // на целите променливи a и b
    cout << "a, b =  ";
    int a, b;
    cin >> a >> b;
    // извеждане на стойностите на променливите a и b
    cout << a << " " << b << endl;
    // намиране на минималното число
    int min = a;
    if(b < min) min = b;
    // извеждане на минималното число
    cout << "min{" << a << ", " << b << "}= " << min << '\n';
    return 0;
}
