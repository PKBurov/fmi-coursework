#include <iostream.h>
#include <math.h>
const int MAX_SIZE = 50;

int main()
{
    int k;  // брой на точките от [10, MAX_SIZE]
    do
    {
        cout << "k= ";
        cin >> k;
    } while(k < 10 || k > MAX_SIZE);

    // два целочислени масива за координатите на точките
    int x[MAX_SIZE];  // абсциси на точките
    int y[MAX_SIZE];  // ординати на точките

    // въвеждане на k точки с целочислени координати
    // точките трябва да бъдат във втори квадрант
    int i;
    for(i = 0; i <= k - 1; i++)
    {
        cout << "Въведете координати на точка "
                "от втори квадрант!\n";
        do
        {
            cout << "x[" << i << "]= ";
            cin >> x[i];
            cout << "y[" << i << "]= ";
            cin >> y[i];
        } while(x[i] > 0 || y[i] < 0);
    }

    // проверява и съобщава за съвпадащи точки
    i = 0;
    bool foundIdentical = false;
    while(i <= k - 2 && !foundIdentical)
    { 
        int j = i + 1;
        while(j <= k - 1 && !foundIdentical)
        { 
            if(x[i] == x[j] && y[i] == y[j])
            {
                foundIdentical = true;
            }
            j++;
        }
        i++;
    }
    if(foundIdentical)
    {
        cout << "Има поне две съвпадащи точки.\n";
    }
    else
    {
        cout << "Няма съвпадащи точки.\n";
    }

    // проверка дали точките са монотонни
    // по отношение на координатата х
    bool monoton = true;
    i = 1;
    // монотонно растяща
    while(i <= k - 2 && monoton)
    {
        if((x[i - 1] < x[i] && x[i] > x[i + 1]) ||
           (x[i - 1] > x[i] && x[i] < x[i + 1]))
        {
            monoton = false;
        }
        // двете проверки могат да се обединят по следния начин
        // if((x[i - 1] - x[i])*(x[i] - x[i + 1]) < 0)
        //	   monoton = false;
        i++;
    }
    if(monoton)
    {
        cout << "Точките са монотонни по отношение "
                "на координатата х. \n";
    }
    else
    {
        cout << "Точките не са монотонни по отношение "
                "на координатата х. \n";
    }

    // изтриване на точките, които нарушават монотонността
    for(i = 1; i <= k - 2; i++)
    {
        if((x[i - 1] - x[i])*(x[i] - x[i + 1]) < 0)
        {   // точката с абсциса x[i+1] нарушава монотонността
            // изтриване на точката от редицата
            for(int j = i + 1; j <= k - 2; j++)
            {
                x[j] = x[j + 1];
                y[j] = y[j + 1];
            }
            k--;  // намаляване на броя на точките
            i--;
        }
    }

    // извеждане на точките
    for(i = 0; i <= k - 1; i++)
    {
        cout << "P" << i << " = (" << x[i] << ", "
             << y[i] << ")\n"; 
    }

    // Точките са монотонни по отношение на х
    // Пресмятане на площта на фигурата
    // между начупената линия и абсцисната ос
    // чрез разбиване областта на трапеци
    double totalArea = 0;          // общата площ на областта
    double currentTrapezium = 0;   // площта на текущия трапец
    for(i = 0; i <= k - 2; i++)
    {
        currentTrapezium = ((double)(y[i]+y[i + 1]) * abs(x[i] - x[i + 1]))/2;
        totalArea = totalArea + currentTrapezium;
    }
    cout << "Общата площ на областта е " 
         << totalArea << "\n";
    return 0;
}
