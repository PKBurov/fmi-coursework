#include <iostream.h>

int main()
{
    // координатите на първата точка
    int x1, y1;
    do
    {
        cout << "x1= ";
        cin >> x1;
        cout << "y1= ";
        cin >> y1;
    } while(x1 < 1 || x1 > 8 || y1 < 1 || y1 > 8);

    // координатите на втората точка
    int x2, y2;
    do
    {
        cout << "x2= ";
        cin >> x2;
        cout << "y2= ";
        cin >> y2;
    } while(x2 < 1 || x2 > 8 || y2 < 1 || y2 > 8);

    // фигурата е пешка
    // клетките достъпни от първата точка са:
    // (x1 - 1, y1 + 1), (x1, y1 + 1), (x1 + 1, y1 + 1)
    // (x1 - 1, y1 - 1), (x1, y1 - 1), (x1 + 1, y1 - 1)
    if((x1 - 1 == x2 || x1 == x2 || x1 + 1 == x2) &&
        (y1 - 1 == y2 || y1 + 1 == y2))
    {
        cout << "Втората точка е достижима с пешка.\n";
    }
    else
    {
        cout << "Втората точка не е достижима с пешка.\n";
    }
    return 0;
}
