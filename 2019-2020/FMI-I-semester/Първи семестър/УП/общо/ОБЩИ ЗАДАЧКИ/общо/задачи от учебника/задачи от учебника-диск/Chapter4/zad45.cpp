#include <iostream.h>
const int MAX_SIZE = 10;

char sign[4] = {'+', '-', '*', '/'};
int x[MAX_SIZE];

// извеждане на вариация с повторения на елементите
// {'+', '-', '*', '/'} от k-ти клас
void Write(int k, int a[])
{
    for(int i = 0; i < k; i++)
    {
        cout << sign[a[i]] << " ";
    }
    cout << endl;
}

// намиране на стойността на израза
// ( .. ((x[0] sign[a[0]] x[1])
//             sign[a[1]] x[2])
//             sign[a[2]] …   )
// ...         sign[a[k-2]] x[k-1]
int Expression(int k, int a[])
{
    int e = x[0];
    for(int i = 0; i < k; i++)
    {
        switch(sign[a[i]])
        {
        case '+':  e = e + x[i+1]; break;
        case '-':  e = e - x[i+1]; break;
        case '*':  e = e * x[i+1]; break;
        case '/':  e = e / x[i+1];
        }
    }
    return e;
}

// повдигане n на степен m
int Pow_int(int n, int m)
{
    int y = 1;
    for(int i = 1; i <= m; i++)
    {
        y = y*n;
    }
    return y;
}

int main()
{ 
    cout << "Дължина на редицата n: ";
    int n; 
    cin >> n;
    int i;

    // въвеждане на редицата
    cout << "Въведете елементите на редицата - "
            "различни от 0 цели числа!\n";
    for(i = 0; i < n; i++)
    {
        do
        { 
            cout << "x[" << i << "]= ";
            cin >> x[i];
        }while(x[i] == 0);
    }

    cout << "Въведете стойност на p! ";
    int p; 
    cin >> p;

    // носител на вариация с повторения на елементите
    // 0, 1, 2, 3 от n-2-ри клас
    int a[MAX_SIZE-1];

    // конструиране на всички вариации с повторения
    // на елементите 0, 1, 2, 3 от n-2-ри клас
    // конструиране на първата вариация с повторения
    for(i = 0; i < n-1; i++)
    {
        a[i] = 0;
    }

    // пресмятане на стойността на израза за
    // първата вариация на знаци и извеждане
    // ако стойността е равна на p
    int e = Expression(n-1, a);
    if(e == p) 
    {
        Write(n-1, a);
    }

    // конструиране на останалите вариации с повторения
    int t = Pow_int(4, n-1);
    for(int j = 1; j < t; j++)
    {
        if(a[n-2] < 3)
        {
            a[n-2] = a[n-2]+1;    // намиране на следваща вариация по правило а)
        }
        else
        { 
            //намиране на следваща вариация по правило б)
            int m = n-2;
            while(a[m] == 3)
            {
                m = m-1;
            }
            a[m] = a[m]+1;
            for(i = m+1; i < n-1; i++)
            {
                a[i] = 0;
            }
        }
    }

    // пресмятане на стойността на израза за
    // поредната вариация на знаци и извеждане,
    // ако стойността е равна на p
    e = Expression(n-1, a);
    if(e == p)    
    {
        Write(n-1, a);
    }
    return 0;
}
