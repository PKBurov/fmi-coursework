#include <iostream.h>

int main()
{
    int x = 0,
        y = 0;
    cout << "Въведете неотрицателно цяло число: ";
    cin >> x;
    cout << "Въведете неотрицателно цяло число: ";
    cin >> y;
    if(y == 0)
    {
        cout << "Свойството " << (x == 0 ? "" : "не ")
             << "е в сила!\n";
    }
    else if(x == 0)
    {
        cout << "Свойството " << (y == 0 ? "" : "не ")
             << "е в сила!\n";
    }
    else
    { 
        // Цикъл за търсене на контрапример, т.е.
        // цифра на x, която не е цифра на y.
        // Когато се наруши поне едно от условията:
        // - y и x имат цифри
        // - няма намерен конрапример
        // цикълът завършва
        while(y != 0 && x != 0 && x % 10 <= y % 10)
        { 
            // най-голямата цифра на x е по-малка
            // от най-голямата цифра на y. Следователно
            // най-голямата цифра на y повече не е
            // необходима, т.е. няма как да стане равна
            // на някоя цифра на x
            if(x % 10 < y % 10)
            {
                y /= 10;
            }
            // Тази цифра на x не може да е контрапример
            if(x % 10 == y % 10)
            {
                x /= 10;
            }
            // на всяка стъпка от този
            // цикъл намалява големината
            // на поне едно от числата и
            // следователно цикълът завършва
        }
        if(x % 10 > y % 10)
        {
            cout << "Свойството не е в сила.\n";
        }
        else
        {
            cout << "Свойството е в сила.\n ";
        }
    }
    return 0;
}
