#include <iostream.h>
const int MAX_SIZE = 10;

int main()
{
    cout << "Въведете стойност на размерността "
            "на A в интервала [1, " << MAX_SIZE << "]: ";
    int n;
    cin >> n;
    int a[MAX_SIZE][MAX_SIZE];

    // Въвеждане на матрицата A
    int i, j;
    cout << "Въведете " << n << " реда с по "
         << n << " цели числа.\n";
    for(i = 0; i < n; i++)
    {
        for(j = 0; j < n; j++)
        {
            cin >> a[i][j];
        }
    }

    // намиране на номера на първия неотрицателен елемент
    // (ако съществува),принадлежащ на главния диагонал на A
    i = -1;
    do
    {
        i++;
    }
    while(a[i][i] < 0 && i < n-1);

    if(a[i][i] >= 0)
    {
        cout << i << endl;
    }
    else
    {
        cout << "Не съществува неотрицателен елемент.\n";
    }
    return 0;
}
