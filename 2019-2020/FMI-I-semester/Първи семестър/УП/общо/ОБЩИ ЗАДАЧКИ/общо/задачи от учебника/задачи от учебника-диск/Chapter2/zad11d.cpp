#include <iostream.h>

int main()
{
    double x, y;
    cout << "x= ";
    cin >> x;
    cout << "y= ";
    cin >> y;
    // полукръг с център (0, 0) и радиус 2,
    // разположен над абсцисната ос
    bool c1 = x*x + y*y <= 4 && y >= 0;
    // кръг с център (-1, 0) и радиус 1
    bool c2 = (x + 1)*(x + 1) + y*y <= 1;
    // кръг с център (1, 0) и радиус 1,
    // без да се включва контурът
    bool c3 = (x - 1)*(x - 1) + y*y < 1;

    // !c3 - областта, извън кръга
    if((c1 || c2) && !c3)
    {
        cout << "Точката принадлежи на областта.\n";
    }
    else
    {
        cout << "Точката не принадлежи на областта.\n";
    }
    return 0;
}
