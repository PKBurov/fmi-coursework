#include <iostream.h>
const int MAX_SIZE = 100;

int main()
{
    cout << "Въведете стойност на n – цяло число от 2 до "
         <<  MAX_SIZE << ": ";
    int n; 
    cin >> n;
    int a[MAX_SIZE];

    // Въвеждане на елементите на редицата
    int i;
    for(i = 0; i < n; i++)
    {
        cout << "a[" << i << "]= ";
        cin >> a[i];
    }

    // проверка дали съществуват
    // два последоватени равни елементи
    i = -1;
    do
    {
        i++;
    }while(a[i] != a[i+1] && i < n-2);

    if(a[i] == a[i+1])
    {
        cout << "Има два последователни равни елемента.\n";
    }
    else
    {
        cout << "Няма два последователни равни елемента.\n";
    }
    return 0;
}
