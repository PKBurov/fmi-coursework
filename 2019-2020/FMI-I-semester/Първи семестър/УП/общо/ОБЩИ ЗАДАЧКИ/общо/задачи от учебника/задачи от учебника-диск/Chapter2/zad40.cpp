#include <iostream.h>

int main()
{
    int sum = 0; 	      // натрупва сумата на числата от серията

    // началото на редицата е 2, краят е 100, а стъпката - 3
    for(int i = 2; i <= 100; i += 3)
    {
        sum = sum + i;
    }
    cout << "Сумата на числата от 2 до 100 със стъпка 3 е "
         << sum << endl;
    return 0;
}
