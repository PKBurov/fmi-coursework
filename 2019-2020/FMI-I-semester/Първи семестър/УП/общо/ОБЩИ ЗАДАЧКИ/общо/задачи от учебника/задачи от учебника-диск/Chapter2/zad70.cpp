#include <iostream.h>

int main()
{ 
    int x = 0,
        flags = 0,
        digit = 0;

    cout << "Въведете неотрицателно цяло число: ";
    cin >> x;

    if(x == 0)  // активира се нулевият по ред бит на flags, за да
    {           // се означи наличието на единствена нула в числото
        flags = 1;
    }

    while(x != 0)
    {   // активира се битът, съответстващ
        // на най-дясната цифра на числото
        flags = flags | 1 << x % 10;
        x /= 10;
    }

    // извежда се резултатът
    for(digit = 0; digit < 10; digit ++)
    {
        if(!(flags & 1 << digit))
        {
            cout << "Цифрата " << digit << " не се среща.\n";
        }
    }
    return 0;
}
