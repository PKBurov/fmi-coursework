#include <iostream.h>

int main()
{
    char c;
    cout << "c= "; 
    cin >> c;
    // сравняват се ASCII кодовете на символите
    if(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z')
    {
        cout << "Въведеният символ е малка или "
                "главна латинска буква.\n ";
    }
    else
    {
        cout << "Въведеният символ не е малка или "
                "главна латинска буква.\n ";
    }
    return 0;
}
