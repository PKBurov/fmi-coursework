#include <iostream.h>

int main()
{
    char c1, c2, c3;
    // въвеждане на символи, означаващи цифри
    cout << "c1= ";
    cin >> c1;
    cout << "c2= ";
    cin >> c2;
    cout << "c3= ";
    cin >> c3;
    // намиране на цяло число, съставено от въведените цифри
    int number = ((c1 - '0')*10 + (c2 - '0'))*10 + (c3 - '0');
    cout << "Числото, образувано от въведените цифри е "
         << number << endl;
    return 0;
}
