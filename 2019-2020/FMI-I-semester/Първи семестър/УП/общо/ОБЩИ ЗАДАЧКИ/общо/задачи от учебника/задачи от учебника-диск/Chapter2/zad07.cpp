#include <iostream.h>

int main()
{ 
    double x;
    double y;
    // въвежда координатите на точката
    cout << "x= ";
    cin >> x;
    cout << "y= ";
    cin >> y;	

    if(x == 0 && y == 0)
    { 
        cout << "Точката съвпада с центъра на "
                "координатната система.\n";
        return 0;
    }

    if(x == 0)
    { 
        cout << "Точката лежи на ординатната ос.\n";
        return 0;
    }

    if(y == 0)
    { 
        cout << "Точката лежи на абсцисната ос.\n";
        return 0;
    }

    if(x > 0 && y > 0)
    { 
        cout << "Точката е в първи квадрант.\n";
        return 0;
    }

    if(x < 0 && y > 0)
    { 
        cout << "Точката е във втори квадрант.\n";
        return 0;
    }

    if(x < 0 && y < 0)
    { 
        cout << "Точката е в трети квадрант.\n";
        return 0;
    }

    cout << "Точката е в четвърти квадрант.\n";
    return 0;
}
