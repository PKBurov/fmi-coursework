#include <iostream.h>

int main()
{
    // деклариране и въвеждане на стойности
    // на реалните променливи a и b
    cout << "a, b=  ";
    double a, b;
    cin >> a >> b;
    // извеждане на стойностите на реалните променливи a и b
    cout << a << " " << b << endl;
    // дефиниране на реална помощна променлива c и
    // реализиране на размяната
    double c = a;
    a = b;
    b = c;
    // извеждане на стойностите на a и b след размяната
    cout << a << " " << b << endl;
    return 0;
}
