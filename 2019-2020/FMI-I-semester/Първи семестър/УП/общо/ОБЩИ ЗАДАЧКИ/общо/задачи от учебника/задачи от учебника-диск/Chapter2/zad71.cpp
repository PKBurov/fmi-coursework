#include <iostream.h>

int main()
{ 
    int x = 0,
        flags = 0;
    cout << "Въведете неотрицателно цяло число: ";
    cin >> x;

    while(x != 0 && !(flags & 1 << x % 10))
    {   // активира се битът, съответстващ
        // на най-дясната цифра на числото
        flags = flags | 1 << x % 10;
        x /= 10;
    }

    if(x != 0)
    {
        cout << "Има повтарящи се цифри.\n";
    }
    else
    {
        cout << "Няма повтарящи се цифри.\n";
    }
    return 0;
}
