#include <iostream.h>

int main()
{
    double a, b, c;
    cout << "Въведете страните a, b и c: ";
    cin >> a >> b >> c;

    if(a <= 0 || b <= 0 || c <= 0)
    {
        cout << "Невалидни входни данни!\n";
        return 1;  // изпълнението на програмата завършва
    }

    if(a >= b + c || b >= a + c || c >= a + b)
    {
        cout << "Тези дължини не могат да са "
                "страни на триъгълник!\n";
        return 1;  // изпълнението на програмата завършва
    }

    if(a == b && b == c)
    {
        cout << "Триъгълникът е равностранен.\n";
    }
    else if(a == b || b == c || c == a)
    {
        cout << "Триъгълникът е равнобедрен.\n";
    }
    else
    {
        cout << "Триъгълникът е разностранен.\n";
    }

    double a2 = a * a;
    double b2 = b * b;
    double c2 = c * c;
    if(a2 == b2 + c2 || b2 == a2 + c2 || c2 == a2 + b2)
    {
        cout << "Триъгълникът е правоъгълен.\n";
    }
    else if(a2 > b2 + c2 || b2 > a2 + c2 || c2 > a2 + b2)
    {
        cout << "Триъгълникът е тъпоъгълен.\n";
    }
    else
    {
        cout << "Триъгълникът е остроъгълен!\n";
    }

    return 0;
} 
