# Група 1
# Създава редица от цели числа А, като всеки следващ член се образува по формулата:
# An={1**n, за n%3==0 и n%2==0; и n**3 за всички други стойности на n}
# Функцията връща индексите на първите 10 елемента от редицата, които имат стойност 1

def group_1():
    l=[]
    k=0 # Преброява първите 10 елемента от редицата, които имат стойност 1
    n=0 # Поредният индекс в редицата
    while k<10:
        if (n%3==0) & (n%2==0):
            l.append(1**n)
            n+=1
            k+=1
        else:
            l.append(n**3)
            n+=1
    indx=[i for i in range(len(l)) if l[i]==1]
    # indx са индексите, отговарящи на условието
    return [l,indx]

