# Задача за размяна на стойностите на две променливи

def ab_1(x,y):
    # размяна чрез трета променлива
    # x и y са числа
    # функцията връща редица от разменените стойности
    
    c=x
    x=y
    y=c
    #print(x,y)
    return(x,y)
def ab_2(x,y):
    #размяна БЕЗ трета променлива
    x=x+y
    y=x-y
    x=x-y
    return(x,y)
def ab_3(x,y):
    #размяна БЕЗ трета променлива, СЪС средствата на Python
    x,y=y,x
    return(x,y)

a=5
b=3
k=ab_1(a,b)
# Създаваме променлива от тип редица (tupple)с два
# елемента: a и b, чрез функцията ab_1
print(k[0]*5)
# Извежда k-нулевия елемент, умножен по 5, т.е. стойността на а*5
l=ab_2(a,b)
print(l[1])
# Извежда l-първия елемент
m=ab_3(a,b)
print(m[0],m[1])
# Извежда m-нулевия елемент и m-първия елемент, поотделно
print(m)
