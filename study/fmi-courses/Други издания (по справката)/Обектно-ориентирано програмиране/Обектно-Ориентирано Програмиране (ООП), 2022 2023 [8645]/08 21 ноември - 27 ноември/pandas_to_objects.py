import pandas as pd
df=pd.read_csv("data.csv", sep="\t")
print(df.head())

class geodata:
    def __init__(self,data_row):
        # def __init__(self, променливи) - това ни е метода, чрез който ще създаваме нови обекти
        # data_row ще бъде запис (ред) от DataFrame таблица
        # атрибути: year,month,station,farenh,celsius
        # този метод няма return

        # Достъп до колоните чрез .името на колоната:
        self.year=data_row.YEAR_MONTH//100 #int
        self.month=data_row.YEAR_MONTH % 100 #int

        # Достъп до колоните чрез ["името на колоната"]:
        self.station=data_row["STATION_NUMBER"]
        self.farenh=data_row["TEMP_F"]
        self.celsius = data_row["TEMP_C"]

        # Пример за използване на метод от същия
        # клас при инициализирането на стойност за атрибут:
        self.diff=self.Diff(data_row)

    def __repr__(self):
        # винаги трябва да има __repr__ ако искаме да може да print-ваме обектите
        # винаги в returna има някакъв стринг, който представя информацията за целия обект
        txt="Station:%s presented temperatures for %d.%d\n" %(self.station,self.month,self.year)
        txt+="F: %.2f, C: %.2f\n" %(self.farenh,self.celsius)
        return txt
    def Diff(self,dr):
        # пример за допълнителен метод
        # обикновено допълнителните методи са за:
        # --допълнителнителни изчисления
        # --конвертиране
        # --сравняване
        # почти винаги приключват с return
        return dr["TEMP_F"]-dr["TEMP_C"]

