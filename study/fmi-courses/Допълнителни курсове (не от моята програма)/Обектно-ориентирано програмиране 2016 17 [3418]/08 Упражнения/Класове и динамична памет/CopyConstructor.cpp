#include <iostream>

class Test
{
    public:
		// конструктор по подразбиране
        Test()
        {
            std::cout << "Default Test object was created!\n";
        }

		// копиращ конструктор
		// За да създадем копие на вече съществуващ обект...
		
		// Забележете аргумента на конструктора!!!

		// Ако няма &, това означа, че аргументът се предава по стойност.
		// По стойност => вътре във функцията се работи с копие, 
		// което трябва да се създаде от копиращия конструктор.
		// (Т.е. за да дефинираме копиращ конструктор, трябва да използваме самия него...)
		
		// Ако пропуснете const, не можете да създавате копия на константни обекти...
        Test(const Test& other)
        {
			std::cout << "Test object was copied\n";
        }

		// Деструктор
		// Извиква се автоматично, когато обектът излезе от област 
		// на видимост и трябва да бъде унищожен
        ~Test()
        {
			std::cout << "~Test()\n";
        }
};

// Предаване по псевдоним, няма копие, закачаме се директно
// за обекта, който е подаден като аргумент
void f(const Test& t)
{
	std::cout << "f()\n";
}

// Предаването на аргумента на функцията е по СТОЙНОСТ,
// което означава, че вътре във функцията се работи с копие.
// За да се създаде това копие се използва копиращия конструктор.
void g(Test t)
{
	std::cout << "g()\n";

	// Предаването на аргумента е по псевдоним, няма създаване на копие
    f(t);

	// с приключването на функцията, копието t излиза от област на видимост
	// и трябва да бъде унищожено, ще бъде извикан деструктор
}

int main()
{
	// Създаваме константен обект с конструктора по подразбиране

	// Изрично е константент, за да проверите какво се случва, 
	// ако премахнете const от аргумента на копиращия конструктор...
    const Test t;
	
	// Извикваме функцията g, чиито аргумент се предава по стойност.
	// Тук, преди да се изпише g(), трябва да видите обръщението към
	// копиращия конструктор.
	
    g(t);

	std::cout << "\ng() has finished!\n";

	// след това съобщение трябва да се види и съобщението от 
	// деструктора на константния обект t, създаден в main
}
